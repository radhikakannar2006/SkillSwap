package com.example.skillswapproject.util;

import android.content.Context;
import android.net.Uri;
import android.os.Bundle;
import android.os.CancellationSignal;
import android.util.Log;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.core.content.ContextCompat;
import androidx.credentials.ClearCredentialStateRequest;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.ClearCredentialException;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.NoCredentialException;
import androidx.fragment.app.FragmentActivity;

import com.google.android.gms.common.ConnectionResult;
import com.google.android.gms.common.GoogleApiAvailability;
import com.google.android.libraries.identity.googleid.GetGoogleIdOption;
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;
import com.google.firebase.auth.AuthCredential;
import com.google.firebase.auth.GoogleAuthProvider;

/**
 * Helper class that encapsulates the Android Credential Manager API for Google Sign-In.
 *
 * Implements the official 3-tier cascade:
 * Tier A: GetGoogleIdOption with filterByAuthorizedAccounts(true)
 * Tier B (Fallback): GetGoogleIdOption with filterByAuthorizedAccounts(false) as a separate single-option request
 * Tier C (Explicit Button): GetSignInWithGoogleOption as a dedicated single-option request
 */
public final class GoogleAuthHelper {

    private static final String TAG = "GoogleAuthHelper";

    private GoogleAuthHelper() {}

    public interface GoogleAuthCallback {
        void onSuccess(@NonNull AuthCredential credential,
                       @Nullable String displayName,
                       @Nullable String email,
                       @Nullable String photoUrl);

        void onCancelled();

        void onError(@NonNull String errorMessage);
    }

    /**
     * Resolves the Web Client ID from resources:
     * 1. default_web_client_id (generated by google-services plugin when client_type 3 is present)
     * 2. google_web_client_id (configured in strings.xml)
     */
    @Nullable
    public static String resolveWebClientId(@NonNull Context context) {
        String webClientId = null;
        try {
            int resId = context.getResources().getIdentifier("default_web_client_id", "string", context.getPackageName());
            if (resId != 0) {
                webClientId = context.getString(resId);
            }
        } catch (Exception ignored) {}

        if (webClientId == null || webClientId.trim().isEmpty()) {
            try {
                int resId = context.getResources().getIdentifier("google_web_client_id", "string", context.getPackageName());
                if (resId != 0) {
                    webClientId = context.getString(resId);
                }
            } catch (Exception ignored) {}
        }

        if (webClientId != null) {
            webClientId = webClientId.trim();
            if (webClientId.isEmpty() || webClientId.startsWith("YOUR_")) {
                return null;
            }
        }
        return webClientId;
    }

    private static String maskClientId(@Nullable String clientId) {
        if (clientId == null || clientId.length() < 12) return "null";
        return clientId.substring(0, 8) + "..." + clientId.substring(clientId.length() - 15);
    }

    /**
     * Entry point: Initiates the Google Sign-In cascade.
     * First checks Google Play Services availability, resolves Web Client ID,
     * and executes Tier A (Authorized Accounts check).
     */
    public static void signIn(@NonNull FragmentActivity activity, @NonNull GoogleAuthCallback callback) {
        String webClientId = resolveWebClientId(activity);
        if (webClientId == null || webClientId.isEmpty()) {
            Log.e(TAG, "signIn: OAuth Web Client ID could not be resolved.");
            callback.onError("Google Sign-In requires your OAuth Web Client ID. Please configure it in strings.xml or add SHA-1 to Firebase Console and re-download google-services.json.");
            return;
        }

        // Verify Google Play Services availability on the physical device
        try {
            int gmsStatus = GoogleApiAvailability.getInstance().isGooglePlayServicesAvailable(activity);
            if (gmsStatus == ConnectionResult.SUCCESS) {
                Log.d(TAG, "Google Play Services verification: SUCCESS.");
            } else {
                Log.w(TAG, "Google Play Services verification: status code " + gmsStatus + ". May affect Credential Manager.");
            }
        } catch (Exception e) {
            Log.w(TAG, "Failed verifying Google Play Services availability: " + e.getMessage());
        }

        Log.i(TAG, "Starting Google Sign-In cascade with Web Client ID: " + maskClientId(webClientId));
        requestAuthorizedGoogleAccount(activity, webClientId, callback);
    }

    /**
     * Tier A: First attempt using GetGoogleIdOption with filterByAuthorizedAccounts(true).
     * Single option only — checks if the user has an existing authorized account for this app.
     */
    private static void requestAuthorizedGoogleAccount(
            @NonNull FragmentActivity activity,
            @NonNull String webClientId,
            @NonNull GoogleAuthCallback callback) {

        Log.d(TAG, "[Tier A] Running: GetGoogleIdOption with filterByAuthorizedAccounts=true");

        GetGoogleIdOption googleIdOption = new GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(true)
                .setServerClientId(webClientId)
                .setAutoSelectEnabled(true)
                .build();

        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build();

        CredentialManager credentialManager = CredentialManager.create(activity);
        CancellationSignal cancellationSignal = new CancellationSignal();

        credentialManager.getCredentialAsync(
                activity,
                request,
                cancellationSignal,
                ContextCompat.getMainExecutor(activity),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse response) {
                        Log.i(TAG, "[Tier A] SUCCESS: Authorized account returned.");
                        handleCredentialResponse(response, callback);
                    }

                    @Override
                    public void onError(GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            Log.d(TAG, "[Tier A] User cancelled account selection.");
                            callback.onCancelled();
                            return;
                        }

                        if (e instanceof NoCredentialException) {
                            Log.i(TAG, "[Tier A] NoCredentialException (no previously authorized account). Falling back to Tier B (all device accounts)...");
                            requestAllGoogleAccounts(activity, webClientId, callback);
                            return;
                        }

                        Log.e(TAG, "[Tier A] FAILED: " + e.getClass().getSimpleName() + " - " + e.getMessage());
                        handleCredentialError(e, callback);
                    }
                }
        );
    }

    /**
     * Tier B: Fallback attempt using GetGoogleIdOption with filterByAuthorizedAccounts(false).
     * Single option only — prompts the user to select from any Google account registered on the device.
     */
    private static void requestAllGoogleAccounts(
            @NonNull FragmentActivity activity,
            @NonNull String webClientId,
            @NonNull GoogleAuthCallback callback) {

        Log.d(TAG, "[Tier B] Running: GetGoogleIdOption with filterByAuthorizedAccounts=false (all device accounts)");

        GetGoogleIdOption googleIdOption = new GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(webClientId)
                .setAutoSelectEnabled(false)
                .build();

        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build();

        CredentialManager credentialManager = CredentialManager.create(activity);
        CancellationSignal cancellationSignal = new CancellationSignal();

        credentialManager.getCredentialAsync(
                activity,
                request,
                cancellationSignal,
                ContextCompat.getMainExecutor(activity),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse response) {
                        Log.i(TAG, "[Tier B] SUCCESS: Account selected from device accounts.");
                        handleCredentialResponse(response, callback);
                    }

                    @Override
                    public void onError(GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            Log.d(TAG, "[Tier B] User cancelled account selection.");
                            callback.onCancelled();
                            return;
                        }

                        if (e instanceof NoCredentialException) {
                            Log.i(TAG, "[Tier B] NoCredentialException from GetGoogleIdOption(false). Falling back to Tier C (explicit GetSignInWithGoogleOption)...");
                            requestExplicitSignInWithGoogle(activity, webClientId, callback);
                            return;
                        }

                        Log.e(TAG, "[Tier B] FAILED: " + e.getClass().getSimpleName() + " - " + e.getMessage());
                        handleCredentialError(e, callback);
                    }
                }
        );
    }

    /**
     * Tier C: Explicit button flow using GetSignInWithGoogleOption as a separate dedicated request.
     * Guaranteed to trigger the standard Google Account Chooser bottom sheet on devices requiring explicit SIWG.
     */
    private static void requestExplicitSignInWithGoogle(
            @NonNull FragmentActivity activity,
            @NonNull String webClientId,
            @NonNull GoogleAuthCallback callback) {

        Log.d(TAG, "[Tier C] Running: Separate explicit button request with GetSignInWithGoogleOption");

        GetSignInWithGoogleOption siwgOption = new GetSignInWithGoogleOption.Builder(webClientId)
                .build();

        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(siwgOption)
                .build();

        CredentialManager credentialManager = CredentialManager.create(activity);
        CancellationSignal cancellationSignal = new CancellationSignal();

        credentialManager.getCredentialAsync(
                activity,
                request,
                cancellationSignal,
                ContextCompat.getMainExecutor(activity),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse response) {
                        Log.i(TAG, "[Tier C] SUCCESS: Credential returned from explicit SIWG button flow.");
                        handleCredentialResponse(response, callback);
                    }

                    @Override
                    public void onError(GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            Log.d(TAG, "[Tier C] User cancelled explicit SIWG bottom sheet.");
                            callback.onCancelled();
                            return;
                        }

                        Log.e(TAG, "[Tier C] FAILED: " + e.getClass().getSimpleName() + " - " + e.getMessage());
                        handleCredentialError(e, callback);
                    }
                }
        );
    }

    private static void handleCredentialResponse(
            @NonNull GetCredentialResponse response,
            @NonNull GoogleAuthCallback callback) {

        if (response == null || response.getCredential() == null) {
            Log.e(TAG, "handleCredentialResponse: Response or credential was null.");
            callback.onError("No credentials returned from Google account selector.");
            return;
        }

        Credential credential = response.getCredential();
        Log.i(TAG, "Credential received: Class=" + credential.getClass().getSimpleName() + ", Type=" + credential.getType());

        if (credential instanceof CustomCredential) {
            CustomCredential customCredential = (CustomCredential) credential;
            String type = customCredential.getType();

            if (GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(type)
                    || GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_SIWG_CREDENTIAL.equals(type)) {

                String idToken = null;
                String email = null;
                String displayName = null;
                String photoUrl = "";

                try {
                    GoogleIdTokenCredential googleIdTokenCredential =
                            GoogleIdTokenCredential.createFrom(customCredential.getData());
                    idToken = googleIdTokenCredential.getIdToken();
                    email = googleIdTokenCredential.getId();
                    displayName = googleIdTokenCredential.getDisplayName();
                    Uri photoUri = googleIdTokenCredential.getProfilePictureUri();
                    photoUrl = photoUri != null ? photoUri.toString() : "";
                } catch (Exception e) {
                    Log.w(TAG, "GoogleIdTokenCredential.createFrom failed: " + e.getMessage() + ". Extracting directly from Bundle.");
                    Bundle data = customCredential.getData();
                    if (data != null) {
                        idToken = data.getString("com.google.android.libraries.identity.googleid.BUNDLE_KEY_ID_TOKEN");
                        email = data.getString("com.google.android.libraries.identity.googleid.BUNDLE_KEY_ID");
                        displayName = data.getString("com.google.android.libraries.identity.googleid.BUNDLE_KEY_DISPLAY_NAME");
                        Uri photoUri = data.getParcelable("com.google.android.libraries.identity.googleid.BUNDLE_KEY_PROFILE_PICTURE_URI");
                        photoUrl = photoUri != null ? photoUri.toString() : "";
                    }
                }

                if (idToken == null || idToken.trim().isEmpty()) {
                    Log.e(TAG, "Extracted ID token is null or empty.");
                    callback.onError("Unable to obtain Google ID token. Please check configuration.");
                    return;
                }

                Log.i(TAG, "Google ID token extracted successfully for email: " + (email != null ? email : "unknown"));
                AuthCredential authCredential = GoogleAuthProvider.getCredential(idToken, null);
                callback.onSuccess(authCredential, displayName, email, photoUrl);
                return;
            } else {
                Log.w(TAG, "Unrecognized custom credential type: " + type);
            }
        }

        Log.e(TAG, "Received unsupported credential: " + credential.getType());
        callback.onError("Received unsupported credential type: " + credential.getType());
    }

    private static void handleCredentialError(
            @NonNull GetCredentialException e,
            @NonNull GoogleAuthCallback callback) {

        String errorType = e.getClass().getSimpleName();
        String msg = e.getMessage() != null ? e.getMessage() : "";
        Log.e(TAG, "Credential Manager terminal error: " + errorType + " - " + msg, e);

        if (e instanceof GetCredentialCancellationException
                || msg.contains("16")
                || msg.contains("CANCELED")
                || msg.contains("cancel")
                || msg.contains("ACTIVITY_DESTROYED")) {
            Log.d(TAG, "Sign-in cancelled by user.");
            callback.onCancelled();
            return;
        }

        if (e instanceof NoCredentialException) {
            callback.onError("No Google accounts found or account selection was dismissed. Please check that a Google account is added to your device (Settings > Google) and try again.");
            return;
        }

        if (msg.contains("10") || msg.contains("DEVELOPER_ERROR") || msg.contains("28433")) {
            callback.onError("Google Sign-In configuration error (Code 10): please verify that the debug SHA-1 fingerprint is registered in Firebase Console.");
        } else if (msg.contains("network") || msg.contains("NETWORK_ERROR") || msg.contains("7")) {
            callback.onError("Network error during Google Sign-In. Please check your internet connection.");
        } else {
            callback.onError("Google Sign-In failed: " + (!msg.isEmpty() ? msg : "Authentication error (" + errorType + ")"));
        }
    }

    /**
     * Clears the Credential Manager session state on logout so the account picker
     * will prompt appropriately upon future sign-in.
     */
    public static void clearCredentialState(@NonNull Context context, @Nullable Runnable onComplete) {
        try {
            CredentialManager credentialManager = CredentialManager.create(context);
            ClearCredentialStateRequest clearRequest = new ClearCredentialStateRequest();
            credentialManager.clearCredentialStateAsync(
                    clearRequest,
                    null,
                    ContextCompat.getMainExecutor(context),
                    new CredentialManagerCallback<Void, ClearCredentialException>() {
                        @Override
                        public void onResult(Void result) {
                            Log.d(TAG, "Credential Manager state cleared successfully.");
                            if (onComplete != null) onComplete.run();
                        }

                        @Override
                        public void onError(ClearCredentialException e) {
                            Log.w(TAG, "Failed clearing Credential Manager state: " + e.getMessage());
                            if (onComplete != null) onComplete.run();
                        }
                    }
            );
        } catch (Exception e) {
            Log.w(TAG, "Exception during clearCredentialState: " + e.getMessage());
            if (onComplete != null) onComplete.run();
        }
    }
}
